export interface SynthesizeSummaryOpts {
  memoryRoot: string;
  llmClient: AIClient;
  /** Wall-clock budget for the LLM call (ms). Default 4 minutes. */
  timeoutMs?: number;
  /** Override the system prompt (test hook). */
  systemPrompt?: string;
}

export interface SynthesizeSummaryResult {
  success: boolean;
  /**
   * Full `summary.md` content. On `success: false` this is the
   * deterministic index fallback (from `generateSummaryMdLive`), so
   * the caller can always write it — Phase 2 no longer owns summary.md.
   */
  content: string;
  error?: string;
}

/**
 * Deterministic fallback when LLM synthesis fails. Guarantees that
 * summary.md is never empty — Phase 2 no longer writes it.
 */
function deterministicFallback(memoryRoot: string): string {
  try {
    const index = generateSummaryMdLive(memoryRoot);
    return index || '# Memory summary\n\n_(empty store)_\n';
  } catch {
    return '# Memory summary\n\n_(empty store)_\n';
  }
}

/**
 * Assemble the LLM input: every canonical file + MEMORY.md, capped.
 */
async function assembleInput(memoryRoot: string): Promise<string> {
  const chunks: Array<{ file: string; content: string }> = [];
  let total = 0;

  for (const dir of ENTITY_DIRS) {
    const abs = path.join(memoryRoot, dir);
    let names: string[];
    try {
      names = await fs.readdir(abs);
    } catch {
      continue;
    }
    for (const name of names.sort()) {
      if (!name.endsWith('.md') || name === 'index.md') continue;
      try {
        const body = await fs.readFile(path.join(abs, name), 'utf8');
        const capped = body.length > MAX_FILE_CHARS
          ? body.slice(0, MAX_FILE_CHARS) + '\n...[truncated]...'
          : body;
        chunks.push({ file: `${dir}/${name}`, content: capped });
        total += capped.length;
      } catch {
        // unreadable — skip
      }
    }
  }

  const memoryPath = path.join(memoryRoot, 'MEMORY.md');
  try {
    const body = await fs.readFile(memoryPath, 'utf8');
    const capped = body.length > 16_000 ? body.slice(0, 16_000) + '\n...[truncated]...' : body;
    chunks.push({ file: 'MEMORY.md', content: capped });
    total += capped.length;
  } catch {
    // MEMORY.md missing — fine, canonical files are the source of truth
  }

  // If we still overflow, drop the largest chunks until we fit.
  if (total > MAX_TOTAL_CHARS) {
    chunks.sort((a, b) => b.content.length - a.content.length);
    let running = 0;
    const kept: Array<{ file: string; content: string }> = [];
    for (const c of chunks) {
      if (running + c.content.length > MAX_TOTAL_CHARS) continue;
      kept.push(c);
      running += c.content.length;
    }
    chunks.splice(0, chunks.length, ...kept);
  }

  return JSON.stringify({ files: chunks }, null, 2);
}

/**
 * Synthesize a semantic `summary.md`. Never throws — always returns a
 * `content` (semantic digest on success, deterministic index fallback on
 * failure) so the caller can write summary.md unconditionally.
 */
export async function synthesizeSummary(
  opts: SynthesizeSummaryOpts,
): Promise<SynthesizeSummaryResult> {
  const timeoutMs = opts.timeoutMs ?? DEFAULT_TIMEOUT_MS;
  const systemPrompt = opts.systemPrompt ?? SYSTEM_PROMPT;
  const fallback = (error: string): SynthesizeSummaryResult => ({
    success: false,
    content: deterministicFallback(opts.memoryRoot),
    error,
  });

  let userPrompt: string;
  try {
    userPrompt = await assembleInput(opts.memoryRoot);
  } catch (err) {
    return fallback(
      `input assembly failed: ${err instanceof Error ? err.message : String(err)}`,
    );
  }

  let raw: string;
  try {
    const messages: Parameters<AIClient['chat']>[0] = [
      { role: 'user', content: userPrompt },
    ];
    const chatResult = await chatWithTimeout(
      opts.llmClient,
      messages,
      { systemPrompt },
      timeoutMs,
    );
    raw = chatResult.content ?? '';
    if (raw.trim().length === 0) {
      return fallback('empty LLM response');
    }
  } catch (err) {
    const msg = err instanceof Error ? err.message : String(err);
    const timedOut = (err as Error).name === 'AbortError' || /aborted/i.test(msg);
    return fallback(
      timedOut ? `llm call timed out after ${timeoutMs}ms` : `llm call failed: ${msg}`,
    );
  }

  let semantic: SemanticSummary;
  try {
    semantic = parseSemanticSummary(raw);
  } catch (err) {
    return fallback(
      `parse failed: ${err instanceof Error ? err.message : String(err)}`,
    );
  }

  try {
    const block = renderSemanticBlock(semantic);
    const index = generateSummaryMdLive(opts.memoryRoot);
    // Insert the semantic block right before the deterministic index's
    // "## Essentials" section so the routing table stays intact below it.
    const marker = '## Essentials';
    const idx = index.indexOf(marker);
    const content =
      idx >= 0
        ? index.slice(0, idx) + block + '\n\n' + index.slice(idx)
        : block + '\n\n' + index;
    return { success: true, content };
  } catch (err) {
    return fallback(
      `render failed: ${err instanceof Error ? err.message : String(err)}`,
    );
  }
}
