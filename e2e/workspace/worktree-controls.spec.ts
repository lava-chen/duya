import { test, expect } from '@playwright/test';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

test('shared checkout UI creates, returns safely, re-enters and removes an unchanged checkout', async ({ page, request }) => {
  const fixture = await request.get('/fixture').then((response) => response.json());
  await page.goto('/');
  await expect(page.locator('.wsl-cwd')).toHaveText(fixture.repo);
  await page.getByRole('textbox', { name: 'Worktree name', exact: true }).fill('browser-result');
  await page.getByRole('button', { name: 'Enter', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Return and keep', exact: true })).toBeVisible();
  const checkout = (await page.locator('.wsl-cwd').textContent())!;
  expect(checkout).not.toBe(fixture.repo);
  expect(readFileSync(path.join(checkout, 'README.md'), 'utf8')).toBe('committed\n');
  writeFileSync(path.join(checkout, 'result.txt'), 'keep this result');
  await page.getByRole('button', { name: 'Return and remove if safe' }).click();
  await expect(page.locator('.wsl-cwd')).toHaveText(fixture.repo);
  await expect(page.getByRole('status')).toContainText('Checkout retained');
  expect(readFileSync(path.join(checkout, 'result.txt'), 'utf8')).toBe('keep this result');
  expect(readFileSync(path.join(fixture.repo, 'README.md'), 'utf8')).toBe('source dirty\n');
  await page.getByRole('combobox').selectOption('existing');
  await page.getByRole('textbox', { name: 'Registered worktree path' }).fill(checkout);
  await page.getByRole('button', { name: 'Enter', exact: true }).click();
  await expect(page.locator('.wsl-cwd')).toHaveText(checkout);
  await page.getByRole('button', { name: 'Return and keep', exact: true }).click();
  await page.getByRole('combobox').selectOption('create');
  await page.getByRole('textbox', { name: 'Worktree name', exact: true }).fill('browser-clean');
  await page.getByRole('button', { name: 'Enter', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Return and keep', exact: true })).toBeVisible();
  const clean = (await page.locator('.wsl-cwd').textContent())!;
  await page.getByRole('button', { name: 'Return and remove if safe' }).click();
  await expect(page.locator('.wsl-cwd')).toHaveText(fixture.repo);
  expect(existsSync(clean)).toBe(false);
  const git = (cwd: string, ...args: string[]) => execFileSync('git', args, { cwd, encoding: 'utf8' }).trim();
  git(fixture.repo, 'add', '.'); git(fixture.repo, 'commit', '-qm', 'source changes');
  await page.getByRole('textbox', { name: 'Worktree name', exact: true }).fill('browser-sync');
  await page.getByRole('textbox', { name: 'New branch (optional)', exact: true }).fill('browser-feature');
  await page.getByRole('button', { name: 'Enter', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Return and keep', exact: true })).toBeVisible();
  const merging = (await page.locator('.wsl-cwd').textContent())!;
  writeFileSync(path.join(merging, 'README.md'), 'feature\n'); git(merging, 'add', '.'); git(merging, 'commit', '-qm', 'feature');
  writeFileSync(path.join(fixture.repo, 'README.md'), 'base\n'); git(fixture.repo, 'add', '.'); git(fixture.repo, 'commit', '-qm', 'base');
  await page.getByRole('textbox', { name: 'Base ref (defaults to HEAD)', exact: true }).fill('main');
  await page.getByRole('button', { name: 'Sync base', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Merge conflicts');
  await page.getByRole('button', { name: 'Abort merge', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Abort merge', exact: true })).toBeHidden();
  expect(readFileSync(path.join(merging, 'README.md'), 'utf8')).toBe('feature\n');
  await page.getByRole('button', { name: 'Return and keep', exact: true }).click();
  await expect(page.locator('.wsl-cwd')).toHaveText(fixture.repo);
  await page.screenshot({ path: test.info().outputPath('checkout-controls.png') });
});
